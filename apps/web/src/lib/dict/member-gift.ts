export type MemberGiftKey = keyof (typeof MEMBER_GIFT_T)["zh"];
export function mg(locale: string, key: MemberGiftKey, vars: Record<string, string | number> = {}): string {
  const table = (MEMBER_GIFT_T as Record<string, Record<MemberGiftKey, string>>)[locale] ?? MEMBER_GIFT_T.en;
  return table[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

/** The note a giver may attach: one line, at most 80 characters, no markup reaches anyone. */
export const GIFT_NOTE_MAX = 80;
export function cleanGiftNote(raw: unknown): string | null {
  if (typeof raw !== "string") return null;
  const s = raw.replace(/[\u0000-\u001f\u007f<>]/g, " ").replace(/\s+/g, " ").trim().slice(0, GIFT_NOTE_MAX);
  return s || null;
}
