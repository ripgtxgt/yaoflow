export type DictKey = keyof (typeof DICT)["zh"];
export type Dictionary = Record<DictKey, string>;

const EXTRA: Partial<Record<Locale, Dictionary>> = {
  "zh-hant": ZH_HANT,
  ja: JA,
  ko: KO,
  fr: FR,
  de: DE,
  es: ES,
  pt: PT,
};

export function dictFor(locale: Locale): Dictionary {
  return (locale === "zh" || locale === "en") ? DICT[locale] : (EXTRA[locale] ?? DICT.en);
}

/** True when this locale has its own dictionary (not the English fallback). */
export function hasDictionary(locale: Locale): boolean {
  return locale === "zh" || locale === "en" || Boolean(EXTRA[locale]);
}

export function t(locale: Locale, key: DictKey, vars?: Record<string, string | number>): string {
  let s: string = dictFor(locale)[key] ?? DICT.en[key];
  // replaceAll, not replace: a sentence may name the same variable twice
  // ("你用{lang}提問，這份解讀就用{lang}寫") and the second one was coming out raw (09-17)
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function isLocale(x: unknown): x is Locale {
  return isKnownLocale(x);
}
